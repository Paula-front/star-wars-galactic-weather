export function getWeekStats(forecast) {
  const temps = forecast.flatMap(d => [d.tempMax, d.tempMin])
  const maxTemps = forecast.map(d => d.tempMax)
  const minTemps = forecast.map(d => d.tempMin)
  return {
    max: Math.max(...maxTemps),
    min: Math.min(...minTemps),
    avg: Math.round(temps.reduce((a, b) => a + b, 0) / temps.length),
    avgMax: Math.round(maxTemps.reduce((a, b) => a + b, 0) / maxTemps.length),
    avgMin: Math.round(minTemps.reduce((a, b) => a + b, 0) / minTemps.length),
  }
}